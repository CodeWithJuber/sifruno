const header = "# Generated by Sifruno from its site database. Do not edit: the next render replaces this file.\n"

// denyRules answer 403 for files that must never be served even when a
// tenant's .htaccess says otherwise; OpenLiteSpeed reads only rewrite rules
// from .htaccess, so Apache "Require"/"Deny" lines there protect nothing.
// Patterns are anchored on "(^|/)" so they match with or without the leading
// slash and in any subdirectory. .well-known stays reachable for ACME, and
// xmlrpc.php is left alone because Jetpack and the mobile apps still use it.
var denyRules = []string{
	`RewriteRule (^|/)\.(ht|git|svn|hg) - [F,L,NC]`,
	`RewriteRule (^|/)\.env - [F,L,NC]`,
	`RewriteRule (^|/)\.user\.ini$ - [F,L,NC]`,
	`RewriteRule (^|/)\.?wp-config\.php(~|\.[^/]*)$ - [F,L,NC]`,
	`RewriteRule (^|/)wp-config\.(bak|old|orig|save|swp|txt)$ - [F,L,NC]`,
	`RewriteRule (^|/)wp-content/debug\.log$ - [F,L,NC]`,
}

// suspendedRules refuse every request, static files included.
var suspendedRules = []string{`RewriteRule .* - [F,L]`}

// acmeChallengeURI is the HTTP-01 path (RFC 8555 section 8.3). Every vhost
// maps it to ACMEChallengeDir.
const acmeChallengeURI = "/.well-known/acme-challenge/"

// Render validates s and returns the managed files keyed by their path
// relative to ServerRoot: ServerConfigPath and one VhostConfigPath per site.
// Equal input in any order gives byte-identical output.
func Render(s Server) (map[string][]byte, error) {
	sites, err := normalize(s)
	if err != nil {
		return nil, err
	}
	sort.Slice(sites, func(i, j int) bool { return sites[i].Name < sites[j].Name })
	listeners := append([]Listener(nil), s.Listeners...)
	sort.Slice(listeners, func(i, j int) bool { return listeners[i].Name < listeners[j].Name })

	files := make(map[string][]byte, len(sites)+1)
	files[ServerConfigPath] = renderServer(listeners, sites)
	for _, v := range sites {
		files[VhostConfigPath(v.Name)] = renderVhost(v)
	}
	for path, data := range files {
		if err := checkLines(data); err != nil {
			return nil, fmt.Errorf("olsweb: rendered %s: %w", path, err)
		}
	}
	return files, nil
}

// VhostConfigPath is a site's vhconf.conf, relative to ServerRoot.
func VhostConfigPath(name string) string {
	return "conf/vhosts/" + NamePrefix + name + "/vhconf.conf"
}

// renderServer writes the server-level fragment: one virtualhost block per
// site, then the listeners with their map lines. A secure listener is left
// out while no site has its own certificate, because it would map no site.
func renderServer(listeners []Listener, sites []site) []byte {
	anyCertificate := false
	for _, v := range sites {
		if v.TLS.CertFile != "" {
			anyCertificate = true
			break
		}
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("# Included from httpd_config.conf by: include " + pathpkg.Join(ServerRoot, ServerConfigPath) + "\n")
	for _, v := range sites {
		enableScript, vhRoot := "1", pathpkg.Join(HomeRoot, v.Username)+"/"
		if v.Suspended {
			enableScript, vhRoot = "0", SuspendedDocRoot+"/"
		}
		b.WriteString("\nvirtualhost " + NamePrefix + v.Name + " {\n")
		kv(&b, "vhRoot", vhRoot)
		kv(&b, "configFile", pathpkg.Join(ServerRoot, VhostConfigPath(v.Name)))
		// restrained keeps static files and symlinks inside vhRoot (the home).
		kv(&b, "allowSymbolLink", "1")
		kv(&b, "enableScript", enableScript)
		kv(&b, "restrained", "1")
		// setUIDMode 2 (DocRoot UID) with user and group runs external apps
		// as the account, not as the server user.
		kv(&b, "setUIDMode", "2")
		kv(&b, "user", v.Username)
		kv(&b, "group", v.Group)
		b.WriteString("}\n")
	}
	for _, l := range listeners {
		if l.Secure && !anyCertificate {
			continue
		}
		addr, _ := listenerAddress(l) // validated by normalize
		b.WriteString("\nlistener " + NamePrefix + l.Name + " {\n")
		kv(&b, "address", addr)
		if l.Secure {
			kv(&b, "secure", "1")
			kv(&b, "keyFile", l.KeyFile)
			kv(&b, "certFile", l.CertFile)
			kv(&b, "certChain", "1")
		} else {
			kv(&b, "secure", "0")
		}
		for _, v := range sites {
			if l.Secure && v.TLS.CertFile == "" {
				continue
			}
			domains := v.Domains
			if l.Secure {
				domains = securedDomains(v)
			}
			kv(&b, "map", NamePrefix+v.Name+" "+strings.Join(domains, ", "))
		}
		b.WriteString("}\n")
	}
	return b.Bytes()
}

// renderVhost writes one site's vhconf.conf. A suspended site keeps its logs
// and certificate but has no PHP handler and refuses every request with 403,
// except ACME challenges: OpenLiteSpeed 1.9.4 serves the challenge context
// (the panel's own folder, never the site's) before the vhost's rewrite rule,
// as the dev VM's broker-site-actions proof shows, so certificate renewal
// keeps working while a site is suspended.
// Its docRoot is SuspendedDocRoot, not the tenant's: every path a suspended
// vhost names (docRoot, logs, certificate, challenge directory) is outside
// every home, so nothing its tenant does can make its config test fail.
func renderVhost(v site) []byte {
	var b bytes.Buffer
	logDir := pathpkg.Join(LogRoot, v.Name)
	state, docRoot := "active", v.DocRoot+"/"
	if v.Suspended {
		state, docRoot = "suspended", SuspendedDocRoot+"/"
	}
	b.WriteString(header)
	b.WriteString("# Site " + v.Name + " (" + state + "), user " + v.Username + ", PHP " + v.PHPVersion + "\n\n")
	kv0(&b, "docRoot", docRoot)
	if !v.Suspended {
		// 2 enables the feature for this vhost; it applies only when the
		// server-level value is not 0. Read from the OpenLiteSpeed 1.9.4
		// source, not yet run: a vhost's cgroups is 1 off or 2 on, and counts
		// only when CGIRLimit's is not 0 (src/http/httpvhost.cpp:3401-3405);
		// CGIRLimit's is 0 disallowed, 1 off by default, 2 on by default
		// (src/http/serverprocessconfig.h:48-50,
		// src/extensions/cgi/cgidworker.cpp:409-416).
		if v.Isolation.Namespace {
			kv0(&b, "namespace", "2")
		}
		if v.Isolation.CGroups {
			kv0(&b, "cgroups", "2")
		}
	}

	b.WriteString("\nindex  {\n")
	kv(&b, "useServer", "0")
	kv(&b, "indexFiles", "index.php, index.html")
	kv(&b, "autoIndex", "0")
	b.WriteString("}\n")

	b.WriteString("\nerrorlog " + pathpkg.Join(logDir, "error.log") + " {\n")
	kv(&b, "useServer", "0")
	kv(&b, "logLevel", "WARN")
	kv(&b, "rollingSize", "10M")
	kv(&b, "keepDays", "30")
	b.WriteString("}\n")

	b.WriteString("\naccesslog " + pathpkg.Join(logDir, "access.log") + " {\n")
	kv(&b, "useServer", "0")
	kv(&b, "logReferer", "1")
	kv(&b, "logUserAgent", "1")
	kv(&b, "rollingSize", "10M")
	kv(&b, "keepDays", "30")
	kv(&b, "compressArchive", "0")
	b.WriteString("}\n")

	if v.TLS.CertFile != "" {
		b.WriteString("\nvhssl  {\n")
		kv(&b, "keyFile", v.TLS.KeyFile)
		kv(&b, "certFile", v.TLS.CertFile)
		kv(&b, "certChain", "1")
		b.WriteString("}\n")
	}

	rules := suspendedRules
	autoLoad := "0"
	if !v.Suspended {
		renderPHP(&b, v)
		rules = append(append([]string(nil), denyRules...), redirectRules(v.Redirects)...)
		autoLoad = "1"
	}
	renderCache(&b, v)
	renderACMEChallenge(&b)
	if !v.Suspended {
		renderFolders(&b, v)
	}

	b.WriteString("\nrewrite  {\n")
	kv(&b, "enable", "1")
	kv(&b, "autoLoadHtaccess", autoLoad)
	kv(&b, "rules", "<<<END_rules")
	for _, r := range rules {
		b.WriteString(r + "\n")
	}
	b.WriteString("  END_rules\n")
	b.WriteString("}\n")
	return b.Bytes()
}

// renderPHP writes the site's own lsphp external app and the handler that
// uses it. Defining both per vhost is what lets OpenLiteSpeed start this
// site's PHP inside its namespace container as the site's user.
func renderPHP(b *bytes.Buffer, v site) {
	name := NamePrefix + v.Name
	children := strconv.Itoa(v.children)
	memory := strconv.Itoa(v.memoryMiB) + "M"
	procs := strconv.Itoa(v.processes)
	b.WriteString("\nextprocessor " + name + " {\n")
	kv(b, "type", "lsapi")
	kv(b, "address", "uds://tmp/lshttpd/"+name+".sock")
	// maxConns equals the LSAPI children so OpenLiteSpeed does not lower it
	// with a warning (localworkerconfig.cpp).
	kv(b, "maxConns", children)
	kv(b, "env", "PHP_LSAPI_CHILDREN="+children)
	kv(b, "env", "LSAPI_AVOID_FORK=200M")
	kv(b, "initTimeout", "60")
	kv(b, "retryTimeout", "0")
	kv(b, "persistConn", "1")
	kv(b, "respBuffer", "0")
	// 2 starts lsphp through the CGI daemon, which is the path that applies
	// the namespace container and cgroups.
	kv(b, "autoStart", "2")
	kv(b, "path", v.phpBinary)
	kv(b, "backlog", "100")
	kv(b, "instances", "1")
	// 0 keeps lsphp attached to the server, so a graceful restart applies a
	// changed PHP version, limit or suspension. The default (3, detached)
	// would keep old processes running until they idle out.
	kv(b, "runOnStartUp", "0")
	kv(b, "extUser", v.Username)
	kv(b, "extGroup", v.Group)
	kv(b, "priority", "0")
	kv(b, "memSoftLimit", memory)
	kv(b, "memHardLimit", memory)
	kv(b, "procSoftLimit", procs)
	kv(b, "procHardLimit", procs)
	b.WriteString("}\n")

	b.WriteString("\nscripthandler  {\n")
	kv(b, "add", "lsapi:"+name+" php")
	b.WriteString("}\n")
}

// cacheSettings are the cache module's vhost-level values for an active site:
// the stock server-level ones, written out so a changed httpd_config.conf
// does not change them. enableCache and enablePrivateCache 0 cache nothing
// by default: a page is cached only when the site's own response asks for it
// (X-LiteSpeed-Cache-Control, which the LiteSpeed Cache WordPress plugin
// sends) or a rewrite rule does. The module never caches a POST.
var cacheSettings = [][2]string{
	{"checkPublicCache", "1"},
	{"checkPrivateCache", "1"},
	{"enableCache", "0"},
	{"enablePrivateCache", "0"},
	{"qsCache", "1"},
	{"reqCookieCache", "1"},
	{"respCookieCache", "1"},
	{"ignoreReqCacheCtrl", "1"},
	{"ignoreRespCacheCtrl", "0"},
	{"expireInSeconds", "3600"},
	{"privateExpireInSeconds", "3600"},
	{"maxStaleAge", "200"},
	{"maxCacheObjSize", "10000000"},
}

// renderCache writes the vhost's "module cache" block. An active site gets
// the module with its own store in CacheRoot, so the purge headers its PHP
// sends act on its own pages only. A suspended site gets the module off and
// nothing to look up: the module serves a cached page when the request
// headers arrive, before the vhost's rewrite rules, so a store left on
// would keep serving the site's pages past its 403 rule.
func renderCache(b *bytes.Buffer, v site) {
	b.WriteString("\nmodule cache {\n")
	if v.Suspended {
		kv(b, "ls_enabled", "0")
		kv(b, "checkPublicCache", "0")
		kv(b, "checkPrivateCache", "0")
		kv(b, "enableCache", "0")
		kv(b, "enablePrivateCache", "0")
		b.WriteString("}\n")
		return
	}
	kv(b, "ls_enabled", "1")
	kv(b, "storagePath", pathpkg.Join(CacheRoot, NamePrefix+v.Name))
	for _, s := range cacheSettings {
		kv(b, s[0], s[1])
	}
	b.WriteString("}\n")
}

// renderACMEChallenge maps the HTTP-01 path to ACMEChallengeDir as static
// files only. allowBrowse is OpenLiteSpeed's "Accessible" switch (0 answers
// 403), not a directory listing, which autoIndex 0 turns off. forceType
// serves every file as text/plain, so no suffix reaches the PHP handler.
// The context's own rewrite block with enable 0 stops OpenLiteSpeed from
// applying a parent context's rules, the tenant's .htaccess among them, and
// from running rules of a .htaccess in the challenge directory. The
// vhost-level rules still run first: none of an active site's deny rules
// matches this path, and a suspended site's rule refuses it like every other
// path.
func renderACMEChallenge(b *bytes.Buffer) {
	b.WriteString("\ncontext " + acmeChallengeURI + " {\n")
	kv(b, "location", ACMEChallengeDir+"/")
	kv(b, "allowBrowse", "1")
	kv(b, "autoIndex", "0")
	kv(b, "forceType", "text/plain")
	b.WriteString("  rewrite  {\n")
	fmt.Fprintf(b, "    %-21s %s\n", "enable", "0")
	b.WriteString("  }\n")
	b.WriteString("}\n")
}

// kv writes one directive inside a block; kv0 writes one at the top level.
func kv(b *bytes.Buffer, key, value string)  { fmt.Fprintf(b, "  %-23s %s\n", key, value) }
func kv0(b *bytes.Buffer, key, value string) { fmt.Fprintf(b, "%-25s %s\n", key, value) }

// checkLines enforces the parser limit that would otherwise drop the file.
func checkLines(data []byte) error {
	for i, line := range bytes.Split(data, []byte("\n")) {
		if len(line)+1 > maxLineBytes {
			return fmt.Errorf("line %d is %d bytes; OpenLiteSpeed refuses lines of 8192 bytes or more", i+1, len(line)+1)
		}
	}
	return nil
}
