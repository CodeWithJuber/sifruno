package dnshost

import (
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

// Zone is one DNS zone in BIND master-file form, the reference's
// /var/named/<domain>.db layout. Records are validated before rendering;
// the file is the truth PowerDNS (bind backend) or named loads.
type Zone struct {
	Domain  string   `json:"domain"`
	Serial  int64    `json:"serial"`
	TTL     int      `json:"ttl"`
	Records []Record `json:"records"`
}

// Record is one zone row. Name is relative ("www") or "@"; Value semantics
// follow the type (MX: "0 mail.example.com.").
type Record struct {
	Name  string `json:"name"`
	Type  string `json:"type"`
	Value string `json:"value"`
	TTL   int    `json:"ttl,omitempty"`
}

var (
	domainRe = regexp.MustCompile(`^(\*\.)?([a-zA-Z0-9_]([a-zA-Z0-9_-]{0,61}[a-zA-Z0-9_])?\.)+[a-zA-Z]{2,}\.?$`)
	nameRe   = regexp.MustCompile(`^(@|\*|[a-zA-Z0-9_]([a-zA-Z0-9._-]{0,253}))$`)
)

var allowedTypes = map[string]bool{
	"A": true, "AAAA": true, "CNAME": true, "MX": true,
	"TXT": true, "NS": true, "SRV": true, "CAA": true, "PTR": true,
}

// ValidateDomain enforces a syntactically valid zone name.
func ValidateDomain(domain string) error {
	if !domainRe.MatchString(domain) {
		return fmt.Errorf("domain %q is not a valid zone name", domain)
	}
	return nil
}

// ValidateRecord checks type whitelist and per-type value shape.
func ValidateRecord(rec Record) error {
	if !nameRe.MatchString(rec.Name) {
		return fmt.Errorf("record name %q is invalid", rec.Name)
	}
	if !allowedTypes[strings.ToUpper(rec.Type)] {
		return fmt.Errorf("record type %q is not supported", rec.Type)
	}
	switch strings.ToUpper(rec.Type) {
	case "A":
		if !ipv4Re.MatchString(rec.Value) {
			return fmt.Errorf("A record value %q is not an IPv4 address", rec.Value)
		}
	case "AAAA":
		if !strings.Contains(rec.Value, ":") {
			return fmt.Errorf("AAAA record value %q is not an IPv6 address", rec.Value)
		}
	case "MX":
		parts := strings.Fields(rec.Value)
		if len(parts) != 2 {
			return fmt.Errorf("MX record value must be \"<priority> <host>\"")
		}
		if _, err := strconv.Atoi(parts[0]); err != nil {
			return fmt.Errorf("MX priority %q is not numeric", parts[0])
		}
	case "CNAME", "NS", "PTR":
		if !domainRe.MatchString(rec.Value) {
			return fmt.Errorf("%s target %q is not a valid hostname", rec.Type, rec.Value)
		}
	}
	return nil
}

var ipv4Re = regexp.MustCompile(`^(\d{1,3}\.){3}\d{1,3}$`)

// NewDefaultZone renders the cPanel-style default zone for a fresh account
// domain: SOA + NS + A (domain, www, mail) + MX + SPF TXT.
func NewDefaultZone(domain, ns1, ns2, ip string) Zone {
	d := strings.TrimSuffix(domain, ".")
	return Zone{
		Domain: d,
		Serial: serialToday(),
		TTL:    14400, // reference default TTL
		Records: []Record{
			{Name: "@", Type: "NS", Value: ns1 + "."},
			{Name: "@", Type: "NS", Value: ns2 + "."},
			{Name: "@", Type: "A", Value: ip},
			{Name: "www", Type: "A", Value: ip},
			{Name: "mail", Type: "A", Value: ip},
			{Name: "@", Type: "MX", Value: "0 " + d + "."},
			{Name: "@", Type: "TXT", Value: `"v=spf1 +a +mx ~all"`},
		},
	}
}

func serialToday() int64 {
	now := time.Now().UTC()
	n, _ := strconv.ParseInt(now.Format("20060102")+"00", 10, 64)
	return n
}

// bumpSerial moves the serial forward (YYYYMMDDnn, nn increments).
func (z *Zone) bumpSerial() {
	today := serialToday()
	if z.Serial < today {
		z.Serial = today
		return
	}
	z.Serial++
}

// Render writes the BIND master file.
func (z Zone) Render(mbox string) string {
	if mbox == "" {
		mbox = "hostmaster." + z.Domain + "."
	}
	var b strings.Builder
	fmt.Fprintf(&b, "; Zone file for %s — generated by sifruno dnshost\n", z.Domain)
	fmt.Fprintf(&b, "$TTL %d\n", z.TTL)
	fmt.Fprintf(&b, "@\tIN\tSOA\t%s %s (\n", nsOf(z), mbox)
	fmt.Fprintf(&b, "\t\t\t%d ; serial\n\t\t\t3600 ; refresh\n\t\t\t1800 ; retry\n\t\t\t1209600 ; expire\n\t\t\t86400 ) ; minimum\n", z.Serial)
	recs := append([]Record{}, z.Records...)
	sort.SliceStable(recs, func(i, j int) bool {
		if recs[i].Type == recs[j].Type {
			return recs[i].Name < recs[j].Name
		}
		return recs[i].Type < recs[j].Type
	})
	for _, r := range recs {
		ttl := r.TTL
		if ttl == 0 {
			ttl = z.TTL
		}
		fmt.Fprintf(&b, "%s\t%d\tIN\t%s\t%s\n", r.Name, ttl, strings.ToUpper(r.Type), r.Value)
	}
	return b.String()
}

func nsOf(z Zone) string {
	for _, r := range z.Records {
		if r.Type == "NS" {
			return r.Value
		}
	}
	return "localhost."
}

// AddRecord validates, appends and bumps the serial.
func (z *Zone) AddRecord(rec Record) error {
	if err := ValidateRecord(rec); err != nil {
		return err
	}
	z.Records = append(z.Records, rec)
	z.bumpSerial()
	return nil
}

// RemoveRecord drops matching rows (name+type[+value]); returns removed count.
func (z *Zone) RemoveRecord(name, typ, value string) int {
	out := z.Records[:0]
	n := 0
	for _, r := range z.Records {
		if r.Name == name && strings.EqualFold(r.Type, typ) && (value == "" || r.Value == value) {
			n++
			continue
		}
		out = append(out, r)
	}
	if n > 0 {
		z.Records = out
		z.bumpSerial()
	}
	return n
}

// Store persists zones as rendered master files plus JSON metadata.
type Store struct {
	Root string // e.g. /srv/sfn-dns (maps to the reference's /var/named)
	// Reload is invoked after Save/Delete when set; errors are logged by
	// callers, zone state is already persisted.
	Reload Reloader
}

func (s *Store) zonePath(domain string) string { return filepath.Join(s.Root, domain+".db") }
func (s *Store) metaPath(domain string) string { return filepath.Join(s.Root, domain+".json") }

func (s *Store) Save(z Zone) error {
	if err := ValidateDomain(z.Domain); err != nil {
		return err
	}
	if err := os.MkdirAll(s.Root, 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(s.zonePath(z.Domain), []byte(z.Render("")), 0o644); err != nil {
		return err
	}
	meta := fmt.Sprintf(`{"domain":%q,"serial":%d,"ttl":%d}`, z.Domain, z.Serial, z.TTL)
	// records live in the rendered file; metadata keeps serial across restarts
	raw, _ := json.Marshal(z)
	_ = meta
	tmp := s.metaPath(z.Domain) + ".tmp"
	if err := os.WriteFile(tmp, raw, 0o644); err != nil {
		return err
	}
	if err := os.Rename(tmp, s.metaPath(z.Domain)); err != nil {
		return err
	}
	if err := s.SyncIndex(); err != nil {
		return err
	}
	if s.Reload != nil {
		_ = s.Reload.Reload()
	}
	return nil
}

func (s *Store) Load(domain string) (Zone, error) {
	var z Zone
	raw, err := os.ReadFile(s.metaPath(domain))
	if err != nil {
		return z, err
	}
	return z, json.Unmarshal(raw, &z)
}

func (s *Store) Delete(domain string) error {
	e1 := os.Remove(s.zonePath(domain))
	e2 := os.Remove(s.metaPath(domain))
	if e1 != nil && !os.IsNotExist(e1) {
		return e1
	}
	if e2 != nil && !os.IsNotExist(e2) {
		return e2
	}
	if err := s.SyncIndex(); err != nil {
		return err
	}
	if s.Reload != nil {
		_ = s.Reload.Reload()
	}
	return nil
}

func (s *Store) List() ([]Zone, error) {
	entries, err := os.ReadDir(s.Root)
	if os.IsNotExist(err) {
		return []Zone{}, nil
	}
	if err != nil {
		return nil, err
	}
	out := []Zone{}
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".json") {
			continue
		}
		z, err := s.Load(strings.TrimSuffix(e.Name(), ".json"))
		if err == nil {
			out = append(out, z)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Domain < out[j].Domain })
	return out, nil
}

// SyncIndex writes a named.conf-style fragment listing every zone —
// the reference's /etc/named.conf include. Called from Save/Delete.
func (s *Store) SyncIndex() error {
	zones, err := s.List()
	if err != nil {
		return err
	}
	var b strings.Builder
	for _, z := range zones {
		fmt.Fprintf(&b, "zone %q { type master; file %q; };\n", z.Domain, s.zonePath(z.Domain))
	}
	if err := os.MkdirAll(s.Root, 0o755); err != nil {
		return err
	}
	tmp := filepath.Join(s.Root, "zones.conf.tmp")
	if err := os.WriteFile(tmp, []byte(b.String()), 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, filepath.Join(s.Root, "zones.conf"))
}

// Reloader notifies the authoritative server after zone changes. Optional:
// nil keeps API behavior unchanged (zones reload on the server's schedule).
type Reloader interface {
	Reload() error
}

// ExecReloader runs one shell command (e.g. HUP the named pid file).
type ExecReloader struct{ Command string }

func (r ExecReloader) Reload() error {
	if r.Command == "" {
		return nil
	}
	cmd := exec.Command("sh", "-c", r.Command)
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("dns reload: %v (%s)", err, strings.TrimSpace(string(out)))
	}
	return nil
}
